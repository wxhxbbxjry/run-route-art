import { RouteData } from './types';
import { haversineDistance } from './geo';

/**
 * Escapes characters for XML safely.
 */
function escapeXml(unsafe: string): string {
  return unsafe.replace(/[<>&'"]/g, (c) => {
    switch (c) {
      case '<':
        return '&lt;';
      case '>':
        return '&gt;';
      case '&':
        return '&amp;';
      case '\'':
        return '&apos;';
      case '"':
        return '&quot;';
      default:
        return c;
    }
  });
}

/**
 * Generates a valid GPX 1.1 XML string ready for Strava, Garmin Connect, and Coros.
 * Includes synchronized timestamps calculated from the user's pace.
 */
export function generateGpx(
  route: RouteData,
  routeName: string = 'Run Route Art',
  paceSecondsPerKm: number = 360 // default 6:00 / km
): string {
  const startTime = new Date();
  let currentTimestamp = startTime.getTime();

  const xmlPoints: string[] = [];

  for (let i = 0; i < route.coordinates.length; i++) {
    const pt = route.coordinates[i];

    if (i > 0) {
      const segDist = haversineDistance(route.coordinates[i - 1], pt);
      const segSeconds = segDist * paceSecondsPerKm;
      currentTimestamp += Math.max(1000, segSeconds * 1000);
    }

    const isoTime = new Date(currentTimestamp).toISOString();

    xmlPoints.push(`      <trkpt lat="${pt.lat.toFixed(7)}" lon="${pt.lng.toFixed(7)}">
        <time>${isoTime}</time>
      </trkpt>`);
  }

  const safeTitle = escapeXml(routeName || 'Run Route Art');
  const safeDesc = escapeXml(
    `Generated by RunRoute PRO. Mode: ${route.mode}. Distance: ${route.distanceKm.toFixed(2)} km`
  );

  return `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="Run Route Art Planner - https://runrouteart.app"
  xmlns="http://www.topografix.com/GPX/1/1"
  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
  xsi:schemaLocation="http://www.topografix.com/GPX/1/1 http://www.topografix.com/GPX/1/1/gpx.xsd">
  <metadata>
    <name>${safeTitle}</name>
    <desc>${safeDesc}</desc>
    <time>${startTime.toISOString()}</time>
  </metadata>
  <trk>
    <name>${safeTitle}</name>
    <desc>${safeDesc}</desc>
    <type>running</type>
    <trkseg>
${xmlPoints.join('\n')}
    </trkseg>
  </trk>
</gpx>`;
}

/**
 * Generates a GeoJSON FeatureCollection string.
 */
export function generateGeoJson(
  route: RouteData,
  routeName: string = 'Run Route Art'
): string {
  const lineCoords = route.coordinates.map((p) => [
    Number(p.lng.toFixed(7)),
    Number(p.lat.toFixed(7)),
  ]);

  const waypointsFeatures = route.waypoints.map((wp, idx) => ({
    type: 'Feature',
    geometry: {
      type: 'Point',
      coordinates: [Number(wp.lng.toFixed(7)), Number(wp.lat.toFixed(7))],
    },
    properties: {
      index: idx + 1,
      id: wp.id,
      name: wp.name || `Waypoint ${idx + 1}`,
      isStart: idx === 0,
      isFinish: idx === route.waypoints.length - 1,
    },
  }));

  const geoJson = {
    type: 'FeatureCollection',
    metadata: {
      name: routeName,
      generator: 'RunRoute PRO',
      distanceKm: Number(route.distanceKm.toFixed(3)),
      mode: route.mode,
      isSnapped: route.isSnapped,
    },
    features: [
      {
        type: 'Feature',
        geometry: {
          type: 'LineString',
          coordinates: lineCoords,
        },
        properties: {
          name: routeName,
          distanceKm: Number(route.distanceKm.toFixed(3)),
        },
      },
      ...waypointsFeatures,
    ],
  };

  return JSON.stringify(geoJson, null, 2);
}

/**
 * Initiates client-side file download.
 */
export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export interface ParsedGpxResult {
  name: string;
  coordinates: { lat: number; lng: number }[];
  totalDistanceKm: number;
}

/**
 * Parses GPX 1.0/1.1 XML string and extracts tracks, routes, waypoints, and distances.
 */
export function parseGpx(gpxText: string): ParsedGpxResult | null {
  if (!gpxText || typeof gpxText !== 'string') return null;

  const rawPoints: { lat: number; lng: number }[] = [];
  let name = 'Rute GPX Terimpor';

  // 1. Try DOMParser (standard in modern browsers)
  if (typeof window !== 'undefined' && window.DOMParser) {
    try {
      const parser = new DOMParser();
      const xmlDoc = parser.parseFromString(gpxText, 'text/xml');

      // Check parse errors
      const parserError = xmlDoc.querySelector('parsererror');
      if (!parserError) {
        // Extract route/track name
        const nameNode =
          xmlDoc.querySelector('trk > name') ||
          xmlDoc.querySelector('metadata > name') ||
          xmlDoc.querySelector('rte > name');
        if (nameNode && nameNode.textContent) {
          name = nameNode.textContent.trim();
        }

        // Extract track points <trkpt> or route points <rtept>
        const ptNodes = xmlDoc.querySelectorAll('trkpt, rtept, wpt');
        ptNodes.forEach((node) => {
          const lat = parseFloat(node.getAttribute('lat') || '');
          const lon = parseFloat(node.getAttribute('lon') || '');
          if (!isNaN(lat) && !isNaN(lon)) {
            rawPoints.push({ lat, lng: lon });
          }
        });
      }
    } catch {
      // fallback to regex below
    }
  }

  // 2. Fallback regex parser if DOMParser failed or empty
  if (rawPoints.length === 0) {
    const nameMatch = gpxText.match(/<name>([^<]+)<\/name>/i);
    if (nameMatch && nameMatch[1]) {
      name = nameMatch[1].trim();
    }

    const ptRegex = /<(?:trkpt|rtept|wpt)\s+[^>]*lat=["']([^"']+)["'][^>]*lon=["']([^"']+)["'][^>]*>[\s\S]*?<\/(?:trkpt|rtept|wpt)>/gi;
    let match: RegExpExecArray | null;

    while ((match = ptRegex.exec(gpxText)) !== null) {
      const lat = parseFloat(match[1]);
      const lng = parseFloat(match[2]);
      if (!isNaN(lat) && !isNaN(lng)) {
        rawPoints.push({ lat, lng });
      }
    }

    // Secondary fallback if self-closing tags
    if (rawPoints.length === 0) {
      const selfCloseRegex = /<(?:trkpt|rtept|wpt)\s+[^>]*lat=["']([^"']+)["'][^>]*lon=["']([^"']+)["'][^>]*\/>/gi;
      while ((match = selfCloseRegex.exec(gpxText)) !== null) {
        const lat = parseFloat(match[1]);
        const lng = parseFloat(match[2]);
        if (!isNaN(lat) && !isNaN(lng)) {
          rawPoints.push({ lat, lng });
        }
      }
    }
  }

  if (rawPoints.length < 2) return null;

  // Filter duplicate points in series
  const cleanCoordinates: { lat: number; lng: number }[] = [];
  for (let i = 0; i < rawPoints.length; i++) {
    const p = rawPoints[i];
    if (
      cleanCoordinates.length > 0 &&
      Math.abs(cleanCoordinates[cleanCoordinates.length - 1].lat - p.lat) < 0.000005 &&
      Math.abs(cleanCoordinates[cleanCoordinates.length - 1].lng - p.lng) < 0.000005
    ) {
      continue;
    }
    cleanCoordinates.push({ lat: p.lat, lng: p.lng });
  }

  if (cleanCoordinates.length < 2) return null;

  // Calculate cumulative distance
  let totalDistanceKm = 0;
  for (let i = 1; i < cleanCoordinates.length; i++) {
    totalDistanceKm += haversineDistance(cleanCoordinates[i - 1], cleanCoordinates[i]);
  }

  return {
    name,
    coordinates: cleanCoordinates,
    totalDistanceKm,
  };
}
